// Cầu nối nhỏ cho trang web trong app: mở hộp thư Business Suite ở cột bên, xem phiên bản và cập nhật app.
const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('metaDesktop', {
  openMetaInbox: url => ipcRenderer.send('open-meta-inbox', String(url)),
  tabChanged: group => ipcRenderer.send('tab-changed', String(group)),
  lookupProfile: args => ipcRenderer.invoke('meta-lookup', args),
  listThreads: args => ipcRenderer.invoke('meta-threads', args),
  hiddenStatus: () => ipcRenderer.invoke('meta-hidden-status'),
  readThread: args => ipcRenderer.invoke('meta-thread-read', args),
  sendThread: args => ipcRenderer.invoke('meta-thread-send', args),
  openZalo: () => ipcRenderer.send('open-zalo'),
  openService: url => ipcRenderer.send('open-svc', url),
  svcApi: args => ipcRenderer.invoke('svc-api', args),
  svcCatalog: args => ipcRenderer.invoke('svc-catalog', args),
  svcImage: url => ipcRenderer.invoke('svc-image', String(url)),
  vaultGet: id => ipcRenderer.invoke('vault-get', String(id)),
  vaultSet: (id, data) => ipcRenderer.invoke('vault-set', String(id), data),
  openThread: args => ipcRenderer.invoke('meta-open-thread', args),
  composePost: args => ipcRenderer.invoke('meta-compose', args),
  loginFacebook: args => ipcRenderer.send('fb-login', args),
  refreshLogin: args => ipcRenderer.invoke('fb-refresh', args),
  lockSettings: () => ipcRenderer.send('app-lock', 'settings'),
  lockNow: () => ipcRenderer.send('app-lock', 'now'),
  lockState: () => ipcRenderer.invoke('lock-state'),
  version: () => ipcRenderer.invoke('app-version'),
  checkUpdate: () => ipcRenderer.invoke('update-check'),
  installUpdate: () => ipcRenderer.invoke('update-install'),
});
